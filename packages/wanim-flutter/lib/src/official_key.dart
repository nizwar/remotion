/// The key of every `.wanim` file without a key of its own.
Uint8List officialKeyBytes() {
  final key = Uint8List(_shareA.length);
  for (var i = 0; i < key.length; i++) {
    key[i] = _shareA[i] ^ _shareB[i];
  }
  return key;
}
